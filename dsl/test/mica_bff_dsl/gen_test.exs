defmodule MicaBffDsl.GenTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  @spec_args ["--spec", "MicaBffDsl.Test.Catalogue", "--namespace", "Test"]

  setup do
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      Mix.shell(Mix.Shell.IO)

      for key <- [:spec, :elixir_namespace, :swift_namespace],
          do: Application.delete_env(:mica_bff_dsl, key)
    end)
  end

  test "a rerun removes stale generated files and keeps hand-written ones", %{tmp_dir: dir} do
    File.write!(Path.join(dir, "old_block.ex"), "# Generated by mica-bff (mix bff.gen.elixir).\n")
    File.write!(Path.join(dir, "helpers.ex"), "# hand-written\n")

    Mix.Tasks.Bff.Gen.Elixir.run(["--out", dir | @spec_args])

    assert dir |> File.ls!() |> Enum.sort() == ["card.ex", "divider.ex", "helpers.ex"]
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    for {task, file} <- [
          {Mix.Tasks.Bff.Gen.Elixir, "card.ex"},
          {Mix.Tasks.Bff.Gen.Swift, "Test.swift"}
        ] do
      path = Path.join(dir, file)
      File.write!(path, "hand-written\n")

      assert_raise Mix.Error, ~r/not generated by mica-bff; not overwriting it/, fn ->
        task.run(["--out", dir | @spec_args])
      end

      assert File.read!(path) == "hand-written\n"
    end
  end

  test "the catalogue and namespaces can come from the config", %{tmp_dir: dir} do
    Application.put_env(:mica_bff_dsl, :spec, MicaBffDsl.Test.Catalogue)
    Application.put_env(:mica_bff_dsl, :elixir_namespace, "Config.Blocks")
    Application.put_env(:mica_bff_dsl, :swift_namespace, "ConfigBlocks")

    Mix.Tasks.Bff.Gen.Elixir.run(["--out", dir])
    Mix.Tasks.Bff.Gen.Swift.run(["--out", dir])

    assert File.read!(Path.join(dir, "card.ex")) =~ "defmodule Config.Blocks.Card do"
    assert File.read!(Path.join(dir, "ConfigBlocks.swift")) =~ "enum ConfigBlocks {}"
  end

  test "there is no default catalogue or namespace", %{tmp_dir: dir} do
    for task <- [Mix.Tasks.Bff.Gen.Elixir, Mix.Tasks.Bff.Gen.Swift] do
      assert_raise Mix.Error, ~r/no spec: pass --spec MODULE/, fn ->
        task.run(["--out", dir, "--namespace", "Test"])
      end

      assert_raise Mix.Error, ~r/no namespace: pass --namespace NAME/, fn ->
        task.run(["--out", dir, "--spec", "MicaBffDsl.Test.Catalogue"])
      end
    end

    assert File.ls!(dir) == []
  end

  test "a spec that isn't a catalogue is refused", %{tmp_dir: dir} do
    for spec <- ["Enum", "No.Such.Module"] do
      assert_raise Mix.Error, ~r/is not a catalogue/, fn ->
        Mix.Tasks.Bff.Gen.Swift.run(["--out", dir, "--spec", spec, "--namespace", "Test"])
      end
    end
  end
end
