defmodule MicaBffDsl.Gen do
  @moduledoc """
  Writes generated files without touching hand-written ones. Every generated
  file starts with a header line containing "Generated by mica-bff".
  """

  @marker "Generated by mica-bff"

  @doc "Whether the file at `path` was written by a mica-bff generator."
  def generated?(path) do
    path |> File.read!() |> String.split("\n", parts: 2) |> hd() |> String.contains?(@marker)
  end

  @doc "Writes `source` to `path`; refuses to overwrite a hand-written file."
  def write!(path, source) do
    if File.exists?(path) and not generated?(path),
      do: Mix.raise("#{path} exists and was not generated by mica-bff; not overwriting it")

    File.write!(path, source)
    Mix.shell().info("* #{path}")
  end

  @doc false
  # The options of `mix bff.gen.*`: `--out` is required; `--spec` and `--namespace`
  # fall back to `config :mica_bff_dsl, spec: ..., <namespace_key>: ...`. There
  # are no defaults: the DSL knows no catalogue.
  def parse_args!(args, namespace_key) do
    {opts, rest} =
      OptionParser.parse!(args, strict: [out: :string, spec: :string, namespace: :string])

    if rest != [], do: Mix.raise("unexpected argument #{Enum.join(rest, " ")}")

    namespace =
      opts[:namespace] || Application.get_env(:mica_bff_dsl, namespace_key) ||
        Mix.raise(
          "no namespace: pass --namespace NAME or set config :mica_bff_dsl, #{namespace_key}: NAME"
        )

    %{
      out: opts[:out] || Mix.raise("--out is required"),
      schema: spec!(opts[:spec] || Application.get_env(:mica_bff_dsl, :spec)).__schema__(),
      namespace: namespace
    }
  end

  defp spec!(nil),
    do: Mix.raise("no spec: pass --spec MODULE or set config :mica_bff_dsl, spec: MODULE")

  defp spec!(name) when is_binary(name), do: spec!(Module.concat([name]))

  defp spec!(module) when is_atom(module) do
    unless Code.ensure_loaded?(module) and function_exported?(module, :__schema__, 0),
      do:
        Mix.raise("#{inspect(module)} is not a catalogue (a module that uses MicaBffDsl.Schema)")

    module
  end
end
