    empty_page = "BFF.Page(emptyList(), emptyList(), emptyList())"

    not_pages =
      for {label, value} <- [
            {"null", nil},
            {"a list", [1]},
            {"no blocks", %{}},
            {"blocks that aren't a list", %{"blocks" => %{"a" => 1}, "markup" => "x"}}
