defmodule MicaBff.Gen.KotlinTest do
  use ExUnit.Case, async: true

  @moduletag :tmp_dir

  test "block, region and type names the generated code needs itself are refused" do
    for name <- [
          :block,
          :unknown_block,
          :region,
          :region_kind,
          :unknown_region,
          :node,
          :block_node,
          :region_node,
          :page,
          :companion
        ],
        schema <- [
          %{blocks: [%{name: name, fields: []}]},
          %{blocks: [], regions: [%{name: name, fields: []}]},
          %{blocks: [], types: [%{name: name, fields: []}]}
        ] do
      assert_raise ArgumentError, ~r/is reserved by Kotlin or the generated code/, fn ->
        MicaBff.Gen.Kotlin.generate(schema)
      end
    end

    assert_raise ArgumentError,
                 ~r/block :api can't be generated in Kotlin: Api is reserved/,
                 fn ->
                   MicaBff.Gen.Kotlin.generate(
                     %{blocks: [%{name: :api, fields: []}]},
                     "bff",
                     "Api"
                   )
                 end
  end

  test "enum fields whose class would shadow the generated code, the namespace or their block are refused" do
    for {name, namespace} <- [block: "BFF", region_kind: "BFF", badge: "BFF", api: "Api"] do
      schema = %{
        blocks: [
          %{
            name: :badge,
            fields: [%{name: name, type: {:enum, [:a]}, required: false, fallback: :a}]
          }
        ]
      }

      assert_raise ArgumentError, ~r/is reserved by Kotlin or the generated code/, fn ->
        MicaBff.Gen.Kotlin.generate(schema, "bff", namespace)
      end
    end
  end

  test "the file starts with the header and its package" do
    source = MicaBff.Gen.Kotlin.generate(MicaBff.Spec.__schema__(), "co.eyra.next.bff", "Api")

    assert [header, "", "package co.eyra.next.bff" | _] = String.split(source, "\n")
    assert header =~ ~r/^\/\/ Generated by mica-bff .*\(mix bff\.gen\.kotlin\)\. Do not edit/
    assert source =~ "\nobject Api {\n"
  end

  # Compiles the generated file with a check program and decodes payloads given as plain
  # Kotlin values. The page fixtures and the rules every client follows
  # (fixtures/rules/markup.json, which the Elixir and Swift tests read too) are in here as
