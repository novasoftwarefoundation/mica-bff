      ),
      block(
        "section begin",
        fixture("section_begin.json"),
        ~s|BFF.SectionBegin(background = "grey6", border = true)|
      ),
      block("section end", fixture("section_end.json"), "BFF.SectionEnd()"),
      block(
        "next best action",
        fixture("next_best_action.json"),
        ~s|BFF.NextBestAction(title = "Complete your profile", body = "Researchers need a few details before you can take part.", cta = "Go to profile", to = "/user/account")|
      ),
      block(
        "reward amount",
        fixture("reward_amount.json"),
        ~s|BFF.RewardAmount(label = "Approved", tone = BFF.RewardAmount.Tone.SUCCESS, amount = "€ 12,50", caption = "You can pay out from € 10,00")|
      ),
      block(
        "advert",
        fixture("advert.json"),
        ~s|BFF.Advert(title = "Sleep and screens", to = "/promotion/7", imageUrl = "https://images.example.org/sleep.jpg", logoUrl = "/images/logos/uu.png", tags = listOf("Health", "Media"), info = "Duration: 10 min. \| Reward: € 2,00")|
