  defp fixture(path), do: Path.join("fixtures", path) |> File.read!() |> JSON.decode!()

  # Check statements for the check program.
  defp expect(label, got, expected), do: "expect(#{kt(label)}, #{got}, #{expected})"
  defp block(label, value, expected), do: expect(label, "BFF.Block.from(#{kt(value)})", expected)

  defp tree(label, page, check, tree),
    do: "tree(#{kt(label)}, BFF.Page.from(#{kt(page)}), #{kt(check)}, #{kt(tree)})"

  defp deep(label, page, check, depth, ids),
    do: "deep(#{kt(label)}, #{page}, #{kt(check)}, #{depth}, #{kt(ids)})"

  # Parsed JSON as the Kotlin literal for the plain values the generated code reads.
  defp kt(nil), do: "null"
  defp kt(value) when is_boolean(value) or is_number(value), do: to_string(value)

  defp kt(string) when is_binary(string) do
    escaped =
      String.replace(string, ["\\", "\"", "$", "\n", "\r", "\t"], fn
        "\n" -> "\\n"
        "\r" -> "\\r"
        "\t" -> "\\t"
        char -> "\\" <> char
      end)

    ~s("#{escaped}")
  end

  defp kt(list) when is_list(list), do: "listOf<Any?>(#{Enum.map_join(list, ", ", &kt/1)})"

  defp kt(map) when is_map(map) do
    pairs = Enum.map_join(map, ", ", fn {key, value} -> "#{kt(key)} to #{kt(value)}" end)
    "mapOf<String, Any?>(#{pairs})"
  end

  # Each check is a function of its own: the JVM limits a method to 64 KB.
  defp run_kotlin!(dir, schema, checks) do
    File.write!(Path.join(dir, "BFF.kt"), MicaBff.Gen.Kotlin.generate(schema))

    functions =
      checks
      |> Enum.with_index()
      |> Enum.map_join("\n", fn {check, index} -> "fun check#{index}() { #{check} }" end)

    calls = Enum.map_join(0..(length(checks) - 1), "\n", &"    check#{&1}()")

    File.write!(Path.join(dir, "Main.kt"), """
    import bff.BFF
    import kotlin.system.exitProcess

    var failed = false

    fun expect(label: String, got: Any?, expected: Any?) {
        if (got != expected) {
            println("FAIL $label: got $got, expected $expected")
            failed = true
        }
    }

    /** A tree in the fixtures' form: a block is its id, a region is its index in the page's markup. */
    fun wire(nodes: List<BFF.Node>, markup: List<BFF.Region>): List<Any?> = nodes.map { node ->
        when (node) {
            is BFF.BlockNode -> node.id
            is BFF.RegionNode -> mapOf(
                "region" to markup.indexOfFirst { it === node.region },
                "children" to wire(node.children, markup),
            )
        }
    }

    fun tree(label: String, page: BFF.Page, check: String?, tree: List<Any?>) {
        expect("$label: check", page.check(), check)
        expect("$label: tree", wire(page.tree(), page.markup), tree)
    }

    fun depth(nodes: List<BFF.Node>): Int =
        nodes.maxOfOrNull { if (it is BFF.RegionNode) 1 + depth(it.children) else 0 } ?: 0

    fun ids(nodes: List<BFF.Node>): List<String?> = nodes.flatMap { node ->
        when (node) {
            is BFF.BlockNode -> listOf(node.id)
            is BFF.RegionNode -> ids(node.children)
        }
    }

    /** A page too deep to write its tree out: its check, the tree's depth and the blocks it shows. */
    fun deep(label: String, page: BFF.Page, check: String?, expectedDepth: Int, blocks: List<Any?>) {
        val tree = page.tree()
        expect("$label: check", page.check(), check)
        expect("$label: depth", depth(tree), expectedDepth)
        expect("$label: blocks", ids(tree), blocks)
    }

    #{functions}

    fun main() {
    #{calls}
        exitProcess(if (failed) 1 else 0)
    }
    """)

    jar = Path.join(dir, "check.jar")

    {out, status} =
      System.cmd("kotlinc", ["BFF.kt", "Main.kt", "-include-runtime", "-d", "check.jar"],
        cd: dir,
        stderr_to_stdout: true
      )

    assert status == 0 and File.exists?(jar), out

    {out, status} = System.cmd(java(), ["-jar", "check.jar"], cd: dir, stderr_to_stdout: true)
    assert status == 0, out
  end

  # macOS has a `java` on the PATH that only says no JDK is installed, so one counts
  # when it runs.
  defp java do
    homes = [System.get_env("JAVA_HOME"), "/opt/homebrew/opt/openjdk@21"]

    candidates =
      [System.find_executable("java")] ++
        for(home <- homes, home, do: Path.join([home, "bin", "java"]))

    Enum.find(candidates, fn java ->
      java && File.exists?(java) &&
        match?({_, 0}, System.cmd(java, ["-version"], stderr_to_stdout: true))
    end) || flunk("no working java on the PATH, in JAVA_HOME or in /opt/homebrew/opt/openjdk@21")
  end
end
