        "unknown kinds",
        ~s|BFF.Page.from(#{kt(%{"markup" => [%{"kind" => "sparkle", "start" => "b", "end" => "a"}, %{"start" => "a", "end" => "a"}]})}).markup|,
        ~s|listOf(BFF.Region("b", "a", BFF.UnknownRegion("sparkle")), BFF.Region("a", "a", BFF.UnknownRegion("")))|
      ),
      tree("no markup", %{"blocks" => [%{"id" => "a", "type" => "section"}]}, nil, ["a"]),
      tree("markup that isn't a list", %{"blocks" => [%{"type" => "x"}], "markup" => 1}, nil, [
        nil
      ])
