defmodule MicaBff.GenTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  setup do
    Mix.shell(Mix.Shell.Process)
    on_exit(fn -> Mix.shell(Mix.Shell.IO) end)
  end

  test "a rerun removes stale generated files and keeps hand-written ones", %{tmp_dir: dir} do
    File.write!(Path.join(dir, "old_block.ex"), "# Generated by mica-bff (mix bff.gen.elixir).\n")
    File.write!(Path.join(dir, "helpers.ex"), "# hand-written\n")

    Mix.Tasks.Bff.Gen.Elixir.run(["--out", dir])

    assert dir |> File.ls!() |> Enum.sort() == ["helpers.ex", "section.ex"]
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    for {task, file} <- [
          {Mix.Tasks.Bff.Gen.Elixir, "section.ex"},
          {Mix.Tasks.Bff.Gen.Swift, "BFF.swift"}
        ] do
      path = Path.join(dir, file)
      File.write!(path, "hand-written\n")

      assert_raise Mix.Error, ~r/not generated by mica-bff; not overwriting it/, fn ->
        task.run(["--out", dir])
      end

      assert File.read!(path) == "hand-written\n"
    end
  end
end
