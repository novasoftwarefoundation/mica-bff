defmodule MicaBff.GenTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  setup do
    Mix.shell(Mix.Shell.Process)
    on_exit(fn -> Mix.shell(Mix.Shell.IO) end)
  end

  @tasks [{Mix.Tasks.Bff.Gen.Swift, "BFF.swift"}, {Mix.Tasks.Bff.Gen.Kotlin, "BFF.kt"}]

  test "generated files name their origin and are recognised on a rerun", %{tmp_dir: dir} do
    for {task, file} <- @tasks do
      task.run(["--out", dir])
      path = Path.join(dir, file)

      assert MicaBff.Gen.generated?(path)

      assert hd(String.split(File.read!(path), "\n")) =~
               ~r/mica-bff \d+\.\d+\.\d+ at [0-9a-f]{7,} /

      # A rerun replaces a generated file.
      task.run(["--out", dir])
    end
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    for {task, file} <- @tasks do
      path = Path.join(dir, file)
      File.write!(path, "hand-written\n")

      assert_raise Mix.Error, ~r/not generated by mica-bff; not overwriting it/, fn ->
        task.run(["--out", dir])
      end

      assert File.read!(path) == "hand-written\n"
    end
  end
end
