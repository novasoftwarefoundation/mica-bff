defmodule MicaBff.Gen do
  @moduledoc """
  Writes generated files without touching hand-written ones. Every generated
  file starts with a header line containing "Generated by mica-bff", followed by
  the version and commit it came from (`origin/0`).
  """

  @marker "Generated by mica-bff"
  @version Mix.Project.config()[:version]

  @doc """
  Where generated code comes from: `"mica-bff 0.1.0 at 9feb740"`, or without the
  commit outside a git checkout.
  """
  def origin do
    case System.find_executable("git") &&
           System.cmd("git", ~w(rev-parse --short HEAD), stderr_to_stdout: true) do
      {sha, 0} -> "mica-bff #{@version} at #{String.trim(sha)}"
      _ -> "mica-bff #{@version}"
    end
  end

  @doc "Whether the file at `path` was written by a mica-bff generator."
  def generated?(path) do
    path |> File.read!() |> String.split("\n", parts: 2) |> hd() |> String.contains?(@marker)
  end

  @doc "Writes `source` to `path`; refuses to overwrite a hand-written file."
  def write!(path, source) do
    if File.exists?(path) and not generated?(path),
      do: Mix.raise("#{path} exists and was not generated by mica-bff; not overwriting it")

    File.write!(path, source)
    Mix.shell().info("* #{path}")
  end
end
