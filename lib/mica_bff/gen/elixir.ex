defmodule MicaBff.Gen.Elixir do
  @default_namespace "Systems.BFF.Blocks"

  @moduledoc """
  Generates one Elixir module per block (namespace `#{@default_namespace}` unless
  given): a struct with the required fields enforced, a typespec, and `to_map/1`,
  which returns the wire shape `%{"type" => ..., "props" => ...}` for any JSON
  library (mica uses Jason). Optional props that are `nil` are left out, as ADR
  0001 requires; `""`, `0`, `false`, `[]` and `%{}` are values and are sent. An
  enum prop is an atom in the struct and its name on the wire; a list is a list.

  The namespace module itself (in `_spec.ex`, a name no block file can have)
  lists the spec's pages: `pages/0` returns `[%{name: :home, path: "/bff/page/home"}]`.
  """

  @types %{string: "String.t()", integer: "integer()", float: "float()", boolean: "boolean()"}

  def default_namespace, do: @default_namespace

  @doc "Returns `{file name, source}` for every block, plus `_spec.ex` with the pages."
  @spec generate(map, String.t()) :: [{String.t(), String.t()}]
  def generate(%{blocks: blocks} = schema, namespace \\ @default_namespace) do
    header = "# Generated by #{MicaBff.Gen.origin()} (mix bff.gen.elixir). Do not edit."

    [{"_spec.ex", generate_spec(Map.get(schema, :pages, []), namespace, header)}] ++
      for block <- blocks, do: {"#{block.name}.ex", generate_block(block, namespace, header)}
  end

  defp generate_spec(pages, namespace, header) do
    """
    #{header}
    defmodule #{namespace} do
      @moduledoc "The BFF spec's pages: each is a GET at its path that returns a flat list of blocks."

      @doc "The pages the BFF serves, in spec order."
      @spec pages() :: [%{name: atom, path: String.t()}]
      def pages, do: #{literal(pages)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp generate_block(%{name: name, fields: fields}, namespace, header) do
    keys = Enum.map(fields, & &1.name)
    {required, optional} = Enum.split_with(fields, & &1.required)
    types = Enum.map_join(fields, ", ", &"#{&1.name}: #{type(&1)}")
    pairs = &Enum.map_join(&1, ", ", fn field -> ~s("#{field.name}" => #{value(field)}) end)
    var = if keys == [], do: "_block", else: "block"

    props =
      if optional == [] do
        "%{#{pairs.(required)}}"
      else
        "Map.merge(%{#{pairs.(required)}}, :maps.filter(fn _key, value -> value != nil end, %{#{pairs.(optional)}}))"
      end

    """
    #{header}
    defmodule #{namespace}.#{Macro.camelize(to_string(name))} do
      @moduledoc "Block `#{name}`."
      @enforce_keys #{literal(Enum.map(required, & &1.name))}
      defstruct #{literal(keys)}

      @type t :: %__MODULE__{#{types}}

      @doc "The wire shape, ready for any JSON encoder."
      @spec to_map(t) :: map
      def to_map(%__MODULE__{} = #{var}), do: %{"type" => "#{name}", "props" => #{props}}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp type(%{required: true} = field), do: base_type(field.type)
  defp type(field), do: "#{base_type(field.type)} | nil"

  defp base_type({:enum, values}), do: Enum.map_join(values, " | ", &inspect/1)
  defp base_type({:list, type}), do: "[#{@types[type]}]"
  defp base_type(type), do: @types[type]

  defp value(%{name: name, type: {:enum, _}, required: true}), do: "Atom.to_string(block.#{name})"

  defp value(%{name: name, type: {:enum, _}}),
    do: "block.#{name} && Atom.to_string(block.#{name})"

  defp value(%{name: name}), do: "block.#{name}"

  # Not inspect/1: its default limit truncates large terms to `...`, which doesn't compile.
  defp literal(term), do: term |> Macro.escape() |> Macro.to_string()
end
