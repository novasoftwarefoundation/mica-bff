defmodule MicaBff.Gen.Swift do
  @moduledoc """
  Generates one Swift file with the block catalogue as `Decodable` types under a
  namespace (default `BFF`; SwiftUI already has a `Section`). One file, because
  the next-ios Xcode project lists every file: it is added once, and new blocks
  only change its content.

  - `enum Block`: one case per block plus `.unknown(type:)`. Decoding never
    fails: an unknown type, or a known block whose props don't decode, becomes
    `.unknown` (ADR 0001), so one bad block never breaks a page.
  - One struct per block. Required fields are non-optional, optional fields are
    Swift optionals, so a missing prop and `null` decode the same. snake_case
    wire names map to camelCase properties; Swift keywords are escaped.

  Views stay hand-written in the app: a `switch` over `Block` without `default:`
  turns a new block in the spec into a build error until it has a view.
  """

  @header "// Generated by mica-bff (mix bff.gen.swift). Do not edit: change the spec in mica-bff and regenerate."
  @types %{string: "String", integer: "Int", float: "Double", boolean: "Bool"}
  @keywords ~w(associatedtype class deinit enum extension fileprivate func import init inout
               internal let open operator private precedencegroup protocol public rethrows static
               struct subscript typealias var break case catch continue default defer do else
               fallthrough for guard if in repeat return throw switch where while as false is nil
               self Self super throws true try Any)

  @doc "Returns the Swift source for the block catalogue."
  @spec generate(map, String.t()) :: String.t()
  def generate(%{blocks: blocks}, namespace) do
    for %{name: name} <- blocks, name in [:block, :unknown] do
      raise ArgumentError, "block #{inspect(name)} clashes with the generated Swift Block enum"
    end

    cases = Enum.map_join(blocks, "\n", &"        case #{ident(&1.name)}(#{type_name(&1.name)})")

    decoders =
      Enum.map_join(blocks, "\n", fn %{name: name} ->
        """
                    case "#{name}":
                        self = (try? container.decode(#{type_name(name)}.self, forKey: .props))
                            .map(Block.#{ident(name)}) ?? .unknown(type: type)\
        """
      end)

    """
    #{@header}

    enum #{namespace} {}

    extension #{namespace} {
        /// One block on a BFF page. Decoding never fails: a type this app doesn't
        /// know, or a known block whose props don't decode, becomes `.unknown`.
        enum Block: Decodable, Equatable, Sendable {
    #{cases}
            case unknown(type: String)

            private enum CodingKeys: String, CodingKey {
                case type, props
            }

            init(from decoder: any Decoder) throws {
                guard let container = try? decoder.container(keyedBy: CodingKeys.self),
                      let type = try? container.decode(String.self, forKey: .type)
                else {
                    self = .unknown(type: "")
                    return
                }
                switch type {
    #{decoders}
                default:
                    self = .unknown(type: type)
                }
            }
        }
    #{Enum.map_join(blocks, "", &block_struct/1)}}
    """
  end

  defp block_struct(%{name: name, fields: fields}) do
    props =
      Enum.map_join(fields, "", fn %{name: field} = f ->
        "        let #{ident(field)}: #{@types[f.type]}#{if f.required, do: "", else: "?"}\n"
      end)

    keys =
      if fields == [] do
        ""
      else
        cases =
          Enum.map_join(fields, "\n", fn %{name: field} ->
            mapped = if camel(field) == to_string(field), do: "", else: ~s( = "#{field}")
            "            case #{ident(field)}#{mapped}"
          end)

        "\n        private enum CodingKeys: String, CodingKey {\n#{cases}\n        }\n"
      end

    """

        /// Block `#{name}`.
        struct #{type_name(name)}: Decodable, Equatable, Sendable {
    #{props}#{keys}    }
    """
  end

  defp type_name(name), do: Macro.camelize(to_string(name))

  defp camel(name) do
    [first | rest] = name |> to_string() |> String.split("_")
    first <> Enum.map_join(rest, &String.capitalize/1)
  end

  defp ident(name) do
    camel = camel(name)
    if camel in @keywords, do: "`#{camel}`", else: camel
  end
end
